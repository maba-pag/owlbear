class TestGenerateDiagramValueError:
    """ValueError from DiagramService.generate is caught and returned as string."""

    @pytest.mark.asyncio
    async def test_value_error_returns_friendly_string(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
    ) -> None:
        """ValueError should be caught and returned as user-friendly message."""
        diagram_svc.generate = AsyncMock(
            side_effect=ValueError("Unsupported diagram type: 'nope'"),
        )
        result = await toolset.generate_diagram(
            diagram_type="nope",
            source="graph TD; A-->B",
            output_format="svg",
        )
        assert isinstance(result, str)
        assert "Invalid input" in result
        assert "Unsupported diagram type" in result

    @pytest.mark.asyncio
    async def test_value_error_does_not_raise(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
    ) -> None:
        """ValueError should NOT propagate — it returns a string instead."""
        diagram_svc.generate = AsyncMock(
            side_effect=ValueError("source must not be empty"),
        )
        result = await toolset.generate_diagram(
            diagram_type="mermaid",
            source="",
            output_format="svg",
        )
        assert isinstance(result, str)

    @pytest.mark.asyncio
    async def test_value_error_skips_save_and_deliver(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
        screenshot_svc: MagicMock,
    ) -> None:
        """When ValueError occurs, save and deliver should NOT be called."""
        diagram_svc.generate = AsyncMock(
            side_effect=ValueError("Unsupported output format: 'bmp'"),
        )
        await toolset.generate_diagram(
            diagram_type="mermaid",
            source="graph TD; A-->B",
            output_format="bmp",
        )
        screenshot_svc.save.assert_not_called()
        screenshot_svc.deliver.assert_not_awaited()
