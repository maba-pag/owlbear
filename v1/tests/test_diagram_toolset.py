class TestGenerateDiagram:
    """generate_diagram calls service, saves, delivers, returns path."""

    @pytest.mark.asyncio
    async def test_calls_diagram_service_generate(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
    ) -> None:
        """Should call DiagramService.generate with correct args."""
        await toolset.generate_diagram(
            diagram_type="mermaid",
            source="graph TD; A-->B",
            output_format="svg",
        )
        diagram_svc.generate.assert_awaited_once_with(
            diagram_type="mermaid",
            source="graph TD; A-->B",
            output_format="svg",
        )

    @pytest.mark.asyncio
    async def test_saves_output_via_screenshot_service(
        self,
        toolset: DiagramToolset,
        screenshot_svc: MagicMock,
        workspace: Path,
    ) -> None:
        """Should save the generated bytes via ScreenshotService.save."""
        await toolset.generate_diagram(
            diagram_type="mermaid",
            source="graph TD; A-->B",
            output_format="svg",
        )
        screenshot_svc.save.assert_called_once()
        args = screenshot_svc.save.call_args[0]
        assert args[0] == b"<svg>diagram</svg>"  # image_bytes
        assert args[1] == "diagram"  # name
        assert args[2] == workspace  # workspace

    @pytest.mark.asyncio
    async def test_delivers_to_channel(
        self,
        toolset: DiagramToolset,
        screenshot_svc: MagicMock,
    ) -> None:
        """Should deliver the saved path to the channel via ScreenshotService.deliver."""
        await toolset.generate_diagram(
            diagram_type="mermaid",
            source="graph TD; A-->B",
            output_format="svg",
        )
        screenshot_svc.deliver.assert_awaited_once()
        call_args = screenshot_svc.deliver.call_args[0]
        assert call_args[0] == Path("/fake/.owlbear/screenshots/12345_diagram.png")

    @pytest.mark.asyncio
    async def test_deliver_caption_includes_diagram_type(
        self,
        toolset: DiagramToolset,
        screenshot_svc: MagicMock,
    ) -> None:
        """Caption passed to deliver should include the diagram_type."""
        await toolset.generate_diagram(
            diagram_type="plantuml",
            source="@startuml\nA -> B\n@enduml",
            output_format="svg",
        )
        caption = screenshot_svc.deliver.call_args[0][2]
        assert "plantuml" in caption

    @pytest.mark.asyncio
    async def test_returns_path_string(
        self,
        toolset: DiagramToolset,
    ) -> None:
        """Should return the string representation of the saved path."""
        result = await toolset.generate_diagram(
            diagram_type="mermaid",
            source="graph TD; A-->B",
            output_format="svg",
        )
        assert result == str(Path("/fake/.owlbear/screenshots/12345_diagram.png"))

    @pytest.mark.asyncio
    async def test_default_output_format_is_svg(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
    ) -> None:
        """output_format should default to 'svg'."""
        await toolset.generate_diagram(
            diagram_type="mermaid",
            source="graph TD; A-->B",
        )
        _, kwargs = diagram_svc.generate.call_args
        assert kwargs["output_format"] == "svg"


