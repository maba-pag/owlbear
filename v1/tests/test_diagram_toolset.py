class TestGenerateDiagramError:
    """DiagramError is caught and returned as a user-friendly string."""

    @pytest.mark.asyncio
    async def test_diagram_error_returns_friendly_string(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
    ) -> None:
        """DiagramError should be caught and returned as user-friendly message."""
        diagram_svc.generate = AsyncMock(
            side_effect=DiagramError(status_code=400, body="Bad syntax"),
        )
        result = await toolset.generate_diagram(
            diagram_type="mermaid",
            source="invalid{{}",
            output_format="svg",
        )
        assert isinstance(result, str)
        assert "400" in result or "Bad syntax" in result

    @pytest.mark.asyncio
    async def test_diagram_error_does_not_raise(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
    ) -> None:
        """DiagramError should NOT propagate — it returns a string instead."""
        diagram_svc.generate = AsyncMock(
            side_effect=DiagramError(status_code=500, body="Internal error"),
        )
        # Should not raise
        result = await toolset.generate_diagram(
            diagram_type="mermaid",
            source="bad",
            output_format="svg",
        )
        assert isinstance(result, str)

    @pytest.mark.asyncio
    async def test_diagram_error_skips_save_and_deliver(
        self,
        toolset: DiagramToolset,
        diagram_svc: MagicMock,
        screenshot_svc: MagicMock,
    ) -> None:
        """When DiagramError occurs, save and deliver should NOT be called."""
        diagram_svc.generate = AsyncMock(
            side_effect=DiagramError(status_code=400, body="Bad syntax"),
        )
        await toolset.generate_diagram(
            diagram_type="mermaid",
            source="bad",
            output_format="svg",
        )
        screenshot_svc.save.assert_not_called()
        screenshot_svc.deliver.assert_not_awaited()


