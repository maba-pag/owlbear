class TestFromAC_FilesystemWalk:
    """AC: filesystem walk with exclusion list."""

    def test_collects_markdown_files(self, tmp_path: Path) -> None:
        """Happy: .md files in an unexcluded directory are returned."""
        doc = _make_md(tmp_path, "README.md")
        result = collect_docs(tmp_path)
        assert doc in result

    def test_collects_excalidraw_files(self, tmp_path: Path) -> None:
        """Happy: .excalidraw diagram files are also collected."""
        diagram = _make_excalidraw(tmp_path, "share/diagrams/overview.excalidraw")
        result = collect_docs(tmp_path)
        assert diagram in result

    def test_ignores_non_doc_file_extensions(self, tmp_path: Path) -> None:
        """Edge: .py, .json, .yaml, and other non-doc files are not collected."""
        py_file = tmp_path / "script.py"
        py_file.write_text("print('hello')")
        json_file = tmp_path / "config.json"
        json_file.write_text("{}")
        result = collect_docs(tmp_path)
        assert py_file not in result
        assert json_file not in result

    @pytest.mark.parametrize("excluded_dir", _EXCLUDED_DIRS)
    def test_excludes_all_exclusion_dirs(
        self, tmp_path: Path, excluded_dir: str
    ) -> None:
        """Boundary: each of the 12 exclusion dirs is skipped during walk."""
        excluded_path = tmp_path / excluded_dir
        excluded_path.mkdir(parents=True, exist_ok=True)
        excluded_doc = excluded_path / "some.md"
        excluded_doc.write_text("# Excluded\n")
        result = collect_docs(tmp_path)
        assert excluded_doc not in result

    def test_excludes_files_nested_inside_excluded_dir(self, tmp_path: Path) -> None:
        """Edge: files nested deeper inside an excluded dir are also excluded."""
        nested = tmp_path / ".owlbear" / "scratch" / "subdir" / "deep.md"
        nested.parent.mkdir(parents=True)
        nested.write_text("# Deep\n")
        result = collect_docs(tmp_path)
        assert nested not in result

    def test_dir_name_prefix_match_is_not_excluded(self, tmp_path: Path) -> None:
        """Boundary: 'store-backup/' shares a prefix with 'store/' but must NOT be excluded."""
        similar = tmp_path / "store-backup" / "README.md"
        similar.parent.mkdir(parents=True)
        similar.write_text("# Backup\n")
        result = collect_docs(tmp_path)
        assert similar in result

    @pytest.mark.parametrize("excluded_name", _EXCLUDED_NAMES)
    def test_excludes_name_based_dirs_at_any_depth(
        self, tmp_path: Path, excluded_name: str
    ) -> None:
        """Boundary: name-based exclusions (node_modules, .venv, etc.) work at any nesting depth."""
        nested = (
            tmp_path / "serve" / "cockpit" / "web" / excluded_name / "pkg" / "README.md"
        )
        nested.parent.mkdir(parents=True)
        nested.write_text("# Nested excluded\n")
        result = collect_docs(tmp_path)
        assert nested not in result

    def test_empty_directory_returns_empty_list(self, tmp_path: Path) -> None:
        """Edge: a tree with no doc files returns an empty list."""
        result = collect_docs(tmp_path)
        assert result == []


