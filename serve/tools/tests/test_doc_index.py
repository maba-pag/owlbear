class TestDocIndexOutboundLinks:
    """AC: outbound link extraction excludes code blocks."""

    def test_prose_links_are_extracted(self, tmp_path: Path) -> None:
        """Happy: [text](url) in regular prose is collected as an outbound link."""
        content = "# Page\n\nSee [the repo](https://github.com/org/repo).\n"
        _make_md(tmp_path, "page.md", content)
        index_path = tmp_path / ".owlbear/doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert "https://github.com/org/repo" in text

    def test_links_in_fenced_code_block_not_extracted(self, tmp_path: Path) -> None:
        """Edge: links inside a fenced code block (``` ... ```) are ignored."""
        content = textwrap.dedent(
            """\
            # Page

            ```markdown
            See [the repo](https://github.com/org/repo).
            ```
            """
        )
        _make_md(tmp_path, "page.md", content)
        index_path = tmp_path / ".owlbear/doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        # The link from inside the code block must NOT appear in Outbound links
        entry_start = text.index("## page.md")
        next_entry = text.find("\n## ", entry_start + 1)
        entry_text = text[entry_start:] if next_entry == -1 else text[entry_start:next_entry]
        assert "https://github.com/org/repo" not in entry_text

    def test_links_in_inline_code_not_extracted(self, tmp_path: Path) -> None:
        """Edge: link-like text inside backtick inline code is not extracted."""
        content = "# Page\n\nRun `[text](https://example.com)` in the terminal.\n"
        _make_md(tmp_path, "page.md", content)
        index_path = tmp_path / ".owlbear/doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        entry_start = text.index("## page.md")
        next_entry = text.find("\n## ", entry_start + 1)
        entry_text = text[entry_start:] if next_entry == -1 else text[entry_start:next_entry]
        assert "https://example.com" not in entry_text

    def test_inline_code_in_link_label_is_preserved(self, tmp_path: Path) -> None:
        """Happy: inline-code formatting in a prose link label reaches the index."""
        content = "# Page\n\nSee [`the repo`](https://github.com/org/repo).\n"
        _make_md(tmp_path, "page.md", content)
        index_path = tmp_path / ".owlbear/doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert "[`the repo`](https://github.com/org/repo)" in text

    def test_link_in_indented_code_block_not_extracted(self, tmp_path: Path) -> None:
        """Boundary: link inside a 4-space-indented code block is not extracted."""
        content = textwrap.dedent(
            """\
            # Page

                [hidden](https://hidden.example.com)

            Normal prose.
            """
        )
        _make_md(tmp_path, "page.md", content)
        index_path = tmp_path / ".owlbear/doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        entry_start = text.index("## page.md")
        next_entry = text.find("\n## ", entry_start + 1)
        entry_text = text[entry_start:] if next_entry == -1 else text[entry_start:next_entry]
        assert "https://hidden.example.com" not in entry_text


