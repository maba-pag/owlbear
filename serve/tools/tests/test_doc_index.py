_WELL_FORMED_INDEX = textwrap.dedent(
    """\
    <!-- AUTO-GENERATED by serve/tools/doc-index. DO NOT EDIT. Regenerated on demand. -->

    ## README.md
    - # `Project Root`
    - ## `Overview`

    ### Outbound links
    - [docs](https://docs.example.com)
    - [repo](https://github.com/org/repo)

    ## docs/guide.md
    - # `Setup Guide`
    - ## `Installation`
    - ## `Configuration`

    ## share/diagrams/overview.excalidraw
    describes: serve/**, share/**
    """
)


class TestFromAC_Parser:
    """AC: parser round-trip — extracts file entries, headings, and outbound links."""

    def test_parser_extracts_file_entry_paths(self) -> None:
        """Happy: parse_index returns an entry for each ## file header in the index."""
        entries = parse_index(_WELL_FORMED_INDEX)
        paths = [e["path"] for e in entries]
        assert "README.md" in paths
        assert "docs/guide.md" in paths
        assert "share/diagrams/overview.excalidraw" in paths

    def test_parser_extracts_headings_from_entry(self) -> None:
        """Happy: each entry's 'headings' list matches the backtick-wrapped bullets."""
        entries = parse_index(_WELL_FORMED_INDEX)
        readme = next(e for e in entries if e["path"] == "README.md")
        assert "# Project Root" in readme["headings"]
        assert "## Overview" in readme["headings"]

    def test_parser_extracts_outbound_links(self) -> None:
        """Happy: links under ### Outbound links are returned in each entry."""
        entries = parse_index(_WELL_FORMED_INDEX)
        readme = next(e for e in entries if e["path"] == "README.md")
        link_targets = [link["target"] for link in readme["outbound_links"]]
        assert "https://docs.example.com" in link_targets
        assert "https://github.com/org/repo" in link_targets

    def test_parser_handles_entry_with_no_outbound_links(self) -> None:
        """Edge: an entry without ### Outbound links returns an empty list for that key."""
        entries = parse_index(_WELL_FORMED_INDEX)
        guide = next(e for e in entries if e["path"] == "docs/guide.md")
        assert guide["outbound_links"] == []

    def test_parser_round_trip_entry_count(self, tmp_path: Path) -> None:
        """Happy: generate_index + parse_index returns one entry per collected doc file."""
        _make_md(tmp_path, "README.md", "# Root\n")
        _make_md(tmp_path, "docs/guide.md", "# Guide\n")
        index_path = tmp_path / "doc-index.md"
        generate_index(tmp_path, index_path)
        entries = parse_index(index_path.read_text())
        assert len(entries) == 2


