_AUTO_GENERATED_HEADER = "<!-- AUTO-GENERATED by serve/tools/doc-index. DO NOT EDIT. Regenerated on demand. -->"


def _make_md(tmp_path: Path, rel: str, content: str = "# Title\n") -> Path:
    """Write a markdown file at *rel* relative to *tmp_path* and return the path."""
    p = tmp_path / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content)
    return p


def _make_excalidraw(tmp_path: Path, rel: str, content: str = "{}") -> Path:
    """Write an Excalidraw file at *rel* relative to *tmp_path* and return the path."""
    p = tmp_path / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content)
    return p


