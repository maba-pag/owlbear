class TestDocIndexMarkdownOutput:
    """AC: markdown output format — header, file headers, heading bullets, links section."""

    def test_output_starts_with_auto_generated_header(self, tmp_path: Path) -> None:
        """Happy: index file starts with the exact auto-generated comment header."""
        _make_md(tmp_path, "README.md", "# Title\n")
        index_path = tmp_path / ".owlbear" / "doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert text.startswith(_AUTO_GENERATED_HEADER)

    def test_output_header_contains_do_not_edit(self, tmp_path: Path) -> None:
        """Happy: header explicitly says DO NOT EDIT."""
        _make_md(tmp_path, "docs/guide.md", "# Guide\n")
        index_path = tmp_path / ".owlbear" / "doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert "DO NOT EDIT" in text

    def test_file_entry_header_uses_relative_path(self, tmp_path: Path) -> None:
        """Happy: each file entry starts with '## <relative-path>' (literal path)."""
        _make_md(tmp_path, "share/agents/README.md", "# Agents\n")
        index_path = tmp_path / ".owlbear" / "doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert "## share/agents/README.md" in text

    def test_manifest_diagram_metadata_is_rendered(self, tmp_path: Path) -> None:
        """Happy: static diagram source, artifact, and source globs reach the index."""
        _make_manifest(
            tmp_path,
            [
                {
                    "source": "share/diagrams/overview.architecture.json",
                    "artifact": "share/diagrams/overview.svg",
                    "describes": ["serve/**", "share/**"],
                }
            ],
        )
        index_path = tmp_path / ".owlbear" / "doc-index.md"

        generate_index(tmp_path)

        text = index_path.read_text()
        assert "## share/diagrams/overview.svg" in text
        assert "source: share/diagrams/overview.architecture.json" in text
        assert "describes: serve/**, share/**" in text

    def test_headings_are_bullet_backtick_wrapped(self, tmp_path: Path) -> None:
        """Happy: headings in a file are emitted as backtick-wrapped bullets."""
        _make_md(
            tmp_path,
            "README.md",
            "# Setup & Installation\n\n## Configuration\n",
        )
        index_path = tmp_path / ".owlbear" / "doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert "- # `Setup & Installation`" in text
        assert "- ## `Configuration`" in text

    def test_outbound_links_subsection_present_when_links_exist(self, tmp_path: Path) -> None:
        """Happy: ### Outbound links sub-section appears when a file has links."""
        _make_md(
            tmp_path,
            "docs/page.md",
            "# Page\n\nSee [project](https://example.com).\n",
        )
        index_path = tmp_path / ".owlbear" / "doc-index.md"
        generate_index(tmp_path)
        text = index_path.read_text()
        assert "### Outbound links" in text

    def test_outbound_links_subsection_absent_when_no_links(self, tmp_path: Path) -> None:
        """Edge: ### Outbound links sub-section is omitted when a file has no links."""
        _make_md(tmp_path, "docs/page.md", "# Page\n\nNo links here.\n")
        index_path = tmp_path / ".owlbear" / "doc-index.md"
        generate_index(tmp_path)
        # The index for this particular file should not have an Outbound links section
        text = index_path.read_text()
        # Find the section for this specific file
        entry_start = text.index("## docs/page.md")
        # Next file section starts with '## ' or end of file
        next_entry = text.find("\n## ", entry_start + 1)
        entry_text = text[entry_start:] if next_entry == -1 else text[entry_start:next_entry]
        assert "### Outbound links" not in entry_text

    def test_relative_outbound_links_are_rebased_to_index(self, tmp_path: Path) -> None:
        """Boundary: generated links resolve from .owlbear/doc-index.md, not their source file."""
        _make_md(tmp_path, "README.md", "# Root\n")
        _make_md(
            tmp_path,
            "serve/example/README.md",
            "# Package\n\n[Root](../../README.md) [Section](#configuration)\n",
        )
        index_path = tmp_path / ".owlbear" / "doc-index.md"

        generate_index(tmp_path)

        text = index_path.read_text()
        entry_start = text.index("## serve/example/README.md")
        next_entry = text.find("\n## ", entry_start + 1)
        entry_text = text[entry_start:] if next_entry == -1 else text[entry_start:next_entry]
        assert "[Root](../README.md)" in entry_text
        assert "[Section](../serve/example/README.md#configuration)" in entry_text


