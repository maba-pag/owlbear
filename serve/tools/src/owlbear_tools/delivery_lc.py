def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def record_hashes(live: Path) -> dict[str, str]:
    """Hash live Delivery records (config, runtime, packages) without following links or worktrees."""
    delivery = live / ".owlbear/delivery"
    hashes: dict[str, str] = {}
    for name in _RECORD_ROOTS:
        root = delivery / name
        paths = [root] if root.is_file() else sorted(path for path in root.rglob("*") if path.is_file())
        for path in paths:
            locator = path.relative_to(delivery).as_posix()
            hashes[locator] = f"symlink:{path.readlink()}" if path.is_symlink() else _sha256(path)
    return hashes


def _copy_tree(source: Path, destination: Path) -> None:
    shutil.copytree(source, destination, symlinks=True, ignore=shutil.ignore_patterns(*_COPY_EXCLUDES))


def prepare(live: Path, stage: Path) -> dict[str, object]:
    """Copy live Git and Delivery state into ``stage/root`` and record live hashes in ``stage/control``."""
    live = live.resolve()
    if stage.exists():
        msg = f"stage already exists: {stage}"
        raise FileExistsError(msg)
    root, control = stage / "root", stage / "control"
    (root / ".owlbear").mkdir(parents=True)
    control.mkdir()
    _copy_tree(live / ".git", root / ".git")
    _copy_tree(live / ".owlbear/delivery", root / ".owlbear/delivery")
    stamp = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    (root / COPY_MARKER).write_text(f"copy-of-{live} {stamp}\n", encoding="utf-8")
    hashes = record_hashes(live)
    (control / "live-before.json").write_text(json.dumps(hashes, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (control / "stage-source").write_text(f"{root.resolve()}\n", encoding="utf-8")
    return {"live": str(live), "stage": str(stage.resolve()), "records": len(hashes)}


def compare(live: Path, stage: Path) -> dict[str, object]:
    """Return whether every live record still has its prepared hash."""
    before = json.loads((stage / "control/live-before.json").read_text(encoding="utf-8"))
    after = record_hashes(live.resolve())
    changed = sorted(locator for locator in set(before) | set(after) if before.get(locator) != after.get(locator))
    return {"live_unchanged": not changed, "changed": changed, "records": len(after)}


@dataclass(frozen=True, slots=True)
class Mount:
    """One ``/proc/self/mountinfo`` row: source ``root``, ``mount_point``, filesystem type and mount source."""

    root: str
    mount_point: str
    fstype: str = ""
    source: str = ""


# Kernel pseudo filesystems: their ``root`` is never a host directory; accepted only under the kernel trees.
_KERNEL_FILESYSTEMS = frozenset(
    {
        "autofs",
        "binfmt_misc",
        "bpf",
        "cgroup",
        "cgroup2",
        "configfs",
        "debugfs",
        "devpts",
        "devtmpfs",
        "efivarfs",
        "fusectl",
        "hugetlbfs",
        "mqueue",
        "nsfs",
        "proc",
        "pstore",
        "securityfs",
        "sysfs",
        "tracefs",
    }
)
_KERNEL_TREES = ("/proc", "/sys", "/dev")
# A bind mount keeps its source filesystem type and a bound tmpfs directory can show ``root`` ``/``, so
# neither proves a fresh instance. Overlay is exempt only as the container root; tmpfs only once each at
# the points the runtime creates itself (runc ``/dev``, ``/dev/shm`` and Docker's masked directories)
# with an anonymous source. Any other tmpfs, under ``/run`` or elsewhere, is inspected like a bind.
_ROOT_FILESYSTEMS = frozenset({"overlay", "fuse.fuse-overlayfs"})
_RUNTIME_TMPFS_POINTS = frozenset(
    {
        "/dev",
        "/dev/shm",  # noqa: S108 - a mount point compared, never a file opened.
        "/proc/acpi",
        "/proc/asound",
        "/proc/scsi",
        "/sys/firmware",
        "/sys/devices/virtual/powercap",
    }
)
_RUNTIME_TMPFS_SOURCES = frozenset({"tmpfs", "shm", "none"})
# Docker Desktop shares a host directory as ``/run/host_mark/<top>``; ``root`` is then relative to it.
_HOST_SHARE = "/run/host_mark"
_HOST_ALIASES = ("/host_mnt", "/private")


def _unescape(field: str) -> str:
    return re.sub(r"\\([0-7]{3})", lambda match: chr(int(match.group(1), 8)), field)


def parse_mountinfo(text: str) -> list[Mount]:
    """Parse mountinfo rows into root, mount point, filesystem type and mount source."""
    mounts = []
    for line in text.splitlines():
        fields = line.split()
        if len(fields) < 5:  # noqa: PLR2004 - mountinfo: id, parent, device, root, mount point.
            continue
        tail = fields[fields.index("-", 5) + 1 :] if "-" in fields[5:] else []
        fstype, source = [*tail, "", ""][:2]
        mounts.append(Mount(_unescape(fields[3]), _unescape(fields[4]), fstype, _unescape(source)))
    return mounts


def _within(path: str, root: str) -> bool:
    return path == root or path.startswith(root.rstrip("/") + "/")


def _without_aliases(path: str) -> str:
    for alias in _HOST_ALIASES:
        if _within(path, alias):
            path = path.removeprefix(alias) or "/"
    return path


def _host_path(mount: Mount) -> str:
    """Return the host directory a mount exposes, joining a Docker Desktop share and removing host aliases."""
    path = mount.root
    if mount.source.startswith(f"{_HOST_SHARE}/"):
        share = mount.source.removeprefix(_HOST_SHARE).rstrip("/")
        path = share if mount.root == "/" else f"{share}{mount.root}"
    return _without_aliases(path)


def _container_mount(mount: Mount, *, stacked: bool) -> bool:
    """Return whether a mount is positively the container root or a runtime-created pseudo mount."""
    if mount.mount_point == "/":
        return mount.fstype in _ROOT_FILESYSTEMS
    if mount.fstype in _KERNEL_FILESYSTEMS:
        return any(_within(mount.mount_point, tree) for tree in _KERNEL_TREES)
    return (
        mount.fstype == "tmpfs"
        and not stacked
        and mount.root == "/"
        and mount.mount_point in _RUNTIME_TMPFS_POINTS
        and mount.source in _RUNTIME_TMPFS_SOURCES
    )


def _exposes_checkout(mount: Mount, live: str, *, stacked: bool) -> bool:
    """Return whether a mount may expose the real checkout or one of its ancestors, at any mount point.

    ``root`` is relative to its own filesystem, whose host mount point is unknown, so any mount whose
    host path is a trailing component sequence of the checkout or an ancestor fails closed.
    """
    if _container_mount(mount, stacked=stacked):
        return False
    exposed = Path(_host_path(mount)).parts[1:]
    checkout = Path(_without_aliases(live)).parts[1:]
    return any(checkout[:end][end - len(exposed) :] == exposed for end in range(len(exposed), len(checkout) + 1))


def _source_matches(root: str, stage_source: str) -> bool:
    candidates = {stage_source, stage_source.removeprefix("/private")}
    return any(root == source or root.endswith(source) for source in candidates)


def isolation_failures(
    mounts: list[Mount],
    *,
    live: str,
    stage_source: str,
    marker_present: bool,
    common_dirs: dict[str, str],
) -> list[str]:
    """Return why the container is not isolated (D9); an empty list proves isolation."""
    failures = []
    at_live = [mount for mount in mounts if _within(mount.mount_point, live)]
    if len(at_live) != 1 or at_live[0].mount_point != live:
        failures.append(f"expected exactly one mount at the live path, found {len(at_live)}")
    elif not _source_matches(_host_path(at_live[0]), stage_source):
        failures.append("the mount at the live path is not the stage copy")
    top = "/" + live.strip("/").split("/", 1)[0]
    outside = [mount for mount in mounts if _within(mount.mount_point, top) and not _within(mount.mount_point, live)]
    if outside:
        failures.append(f"unexpected mounts under {top}: {[mount.mount_point for mount in outside]}")
    points = Counter(mount.mount_point for mount in mounts)
    failures.extend(
        f"the real checkout or an ancestor of it is mounted at {mount.mount_point}"
        for mount in mounts
        if _exposes_checkout(mount, live, stacked=points[mount.mount_point] > 1)
    )
    if not marker_present:
        failures.append("the copy marker is absent at the live path")
    expected = f"{live.rstrip('/')}/.git"
    failures.extend(
        f"{name} resolves Git outside the copy: {resolved}"
        for name, resolved in common_dirs.items()
        if resolved != expected
    )
    return failures


def _git_common_dir(path: Path) -> str:
    completed = subprocess.run(  # noqa: S603 - fixed Git argument vector inside the isolated container.
        ("git", "-C", str(path), "rev-parse", "--path-format=absolute", "--git-common-dir"),  # noqa: S607
        check=False,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip() if completed.returncode == 0 else f"<git failed: {completed.returncode}>"


def prove_isolation(live: Path, stage_source: str) -> dict[str, object]:
    """Inside the container: prove the stage is the only mount at the live path before any load."""
    worktrees = live / ".owlbear/delivery/worktrees"
    common_dirs = {"copy": _git_common_dir(live)}
    if worktrees.is_dir():
        common_dirs.update({child.name: _git_common_dir(child) for child in sorted(worktrees.iterdir())})
    failures = isolation_failures(
        parse_mountinfo(Path("/proc/self/mountinfo").read_text(encoding="utf-8")),
        live=str(live),
        stage_source=stage_source,
        marker_present=(live / COPY_MARKER).is_file(),
        common_dirs=common_dirs,
    )
    return {"isolated": not failures, "failures": failures, "common_dirs": common_dirs}


def docker_command(  # noqa: PLR0913 - one container invocation binds each isolation input explicitly.
    stage: Path,
    live: Path,
    candidate: str,
    form: str,
    previous: str,
    *,
    image: str = DEFAULT_IMAGE,
    uv_cache_volume: str | None = None,
) -> list[str]:
    """Return the container command: the stage copy at the live path and control files at ``/lc`` only."""
    command = ["docker", "run", "--rm", "-v", f"{(stage / 'root').resolve()}:{live}"]
    command += ["-v", f"{(stage / 'control').resolve()}:{CONTROL_MOUNT}"]
    if uv_cache_volume:
        command += ["-v", f"{uv_cache_volume}:/root/.cache/uv"]
    return [*command, image, "sh", f"{CONTROL_MOUNT}/inside.sh", str(live), candidate, form, previous]


def run(  # noqa: PLR0913 - mirrors docker_command.
    stage: Path,
    live: Path,
    candidate: str,
    form: str,
    previous: str,
    *,
    image: str = DEFAULT_IMAGE,
    uv_cache_volume: str | None = None,
    ca_bundle: Path | None = None,
    dry_run: bool = False,
) -> dict[str, object]:
    """Write the container script and run the candidate's LC form against the stage copy.

    ``ca_bundle`` (PEM) is appended to the container trust store, for networks that intercept TLS.
    """
    control = stage / "control"
    (control / "inside.sh").write_text(_INSIDE, encoding="utf-8")
    shutil.copyfile(__file__, control / "delivery_lc.py")
    if ca_bundle is not None:
        shutil.copyfile(ca_bundle, control / CA_BUNDLE)
    command = docker_command(stage, live, candidate, form, previous, image=image, uv_cache_volume=uv_cache_volume)
    if dry_run:
        return {"command": command}
    with (control / "run.log").open("wb") as log:
        completed = subprocess.run(command, check=False, stdout=log, stderr=subprocess.STDOUT)  # noqa: S603
    report = control / "report.json"
    result = json.loads(report.read_text(encoding="utf-8")) if report.is_file() else {}
    return {"exit": completed.returncode, "report": result, "log": str(control / "run.log")}


