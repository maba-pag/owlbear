def _primary_worktree() -> Path:
    completed = subprocess.run(
        ("git", "rev-parse", "--path-format=absolute", "--git-common-dir"),  # noqa: S607
        check=True,
        capture_output=True,
        text=True,
    )
    return Path(completed.stdout.strip()).parent


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="delivery-lc", description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    prepare_parser = commands.add_parser("prepare")
    prepare_parser.add_argument("--stage", type=Path, required=True)
    prepare_parser.add_argument("--live", type=Path, default=None)
    run_parser = commands.add_parser("run")
    run_parser.add_argument("--stage", type=Path, required=True)
    run_parser.add_argument("--live", type=Path, default=None)
    run_parser.add_argument("--candidate", required=True)
    run_parser.add_argument("--form", choices=("load", "full"), required=True)
    run_parser.add_argument("--previous", default="")
    run_parser.add_argument("--image", default=DEFAULT_IMAGE)
    run_parser.add_argument("--uv-cache-volume", default=None)
    run_parser.add_argument("--ca-bundle", type=Path, default=None)
    run_parser.add_argument("--dry-run", action="store_true")
    compare_parser = commands.add_parser("compare")
    compare_parser.add_argument("--stage", type=Path, required=True)
    compare_parser.add_argument("--live", type=Path, default=None)
    proof_parser = commands.add_parser("prove-isolation")
    proof_parser.add_argument("--live", type=Path, required=True)
    proof_parser.add_argument("--stage-source", required=True)
    proof_parser.add_argument("--report", type=Path, required=True)
    inside_parser = commands.add_parser("inside")
    inside_parser.add_argument("--live", type=Path, required=True)
    inside_parser.add_argument("--form", choices=("load", "full"), required=True)
    inside_parser.add_argument("--previous", default="")
    inside_parser.add_argument("--report", type=Path, required=True)
    load_parser = commands.add_parser("load-changes")
    load_parser.add_argument("--live", type=Path, required=True)
    return parser


def _execute(args: argparse.Namespace) -> tuple[int, dict[str, object]]:
    live = getattr(args, "live", None) or _primary_worktree()
    if args.command == "prepare":
        return 0, prepare(live, args.stage)
    if args.command == "compare":
        result = compare(live, args.stage)
        return (0 if result["live_unchanged"] else 1), result
    if args.command == "run":
        if args.form == "full" and not args.previous:
            return 2, {"error": "the full form needs --previous (the merged predecessor phase head)"}
        result: dict[str, Any] = run(
            args.stage,
            live.resolve(),
            args.candidate,
            args.form,
            args.previous,
            image=args.image,
            uv_cache_volume=args.uv_cache_volume,
            ca_bundle=args.ca_bundle,
            dry_run=args.dry_run,
        )
        passed = args.dry_run or (result["exit"] == 0 and result["report"].get("passed") is True)
        return (0 if passed else 1), result
    if args.command == "load-changes":
        result = _load_every_change(live)
        return (0 if result.get("loaded") else 1), result
    if args.command == "prove-isolation":
        result = prove_isolation(live, args.stage_source)
    else:
        result = full_form(live, args.previous) if args.form == "full" else load_form(live)
    args.report.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return (0 if result.get("isolated", result.get("passed")) else 1), result


def main(argv: list[str] | None = None) -> int:
    """Console entry point: print one JSON object; non-zero when the gate fails."""
    code, payload = _execute(_parser().parse_args(argv))
    with contextlib.suppress(BrokenPipeError):
        sys.stdout.write(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    return code


if __name__ == "__main__":  # pragma: no cover - container entry point for the isolation proof.
    raise SystemExit(main())
